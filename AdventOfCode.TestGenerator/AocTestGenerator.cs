using System.Collections.Immutable;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace AdventOfCode.TestGenerator;

[Generator]
public sealed class AocTestGenerator : IIncrementalGenerator
{
    private const string RegistrationNamespace = "AdventOfCode.TestGenerator";
    private const string RegistrationName = "GenerateAocTestsAttribute";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        // The test project supplies its types with typeof, so the generator does not
        // depend on the names or namespaces of the puzzle types.
        context.RegisterPostInitializationOutput(static output =>
            output.AddSource($"{RegistrationName}.g.cs", $$"""
                                                           // <auto-generated />
                                                           namespace {{RegistrationNamespace}};

                                                           [global::System.AttributeUsage(global::System.AttributeTargets.Assembly)]
                                                           internal sealed class {{RegistrationName}} : global::System.Attribute
                                                           {
                                                               public {{RegistrationName}}(global::System.Type dayBase, global::System.Type expectedAnswer)
                                                               {
                                                               }
                                                           }
                                                           """));

        var answers = context.CompilationProvider.SelectMany(static (compilation, cancellationToken) =>
        {
            var results = ImmutableArray.CreateBuilder<(string TypeName, string? Part1, string? Part2)>();
            var registrationType =
                compilation.Assembly.GetTypeByMetadataName($"{RegistrationNamespace}.{RegistrationName}");
            var registration = compilation.Assembly.GetAttributes().FirstOrDefault(attribute =>
                SymbolEqualityComparer.Default.Equals(attribute.AttributeClass, registrationType));

            if (registration is not { ConstructorArguments.Length: 2 } ||
                registration.ConstructorArguments[0].Value is not INamedTypeSymbol baseDayType ||
                registration.ConstructorArguments[1].Value is not INamedTypeSymbol expectedAnswerType)
            {
                return results.ToImmutable();
            }

            VisitNamespace(expectedAnswerType.ContainingAssembly.GlobalNamespace);
            return results.ToImmutable();

            void VisitNamespace(INamespaceSymbol ns)
            {
                cancellationToken.ThrowIfCancellationRequested();

                foreach (var childNamespace in ns.GetNamespaceMembers())
                {
                    VisitNamespace(childNamespace);
                }

                foreach (var type in ns.GetTypeMembers())
                {
                    var attribute = type.GetAttributes().FirstOrDefault(candidate =>
                        SymbolEqualityComparer.Default.Equals(candidate.AttributeClass, expectedAnswerType));

                    if (attribute is not { ConstructorArguments.Length: 2 } || !DerivesFrom(type, baseDayType))
                    {
                        continue;
                    }

                    var part1 = attribute.ConstructorArguments[0].Value as string;
                    var part2 = attribute.ConstructorArguments[1].Value as string;
                    if (part1 is not null || part2 is not null)
                    {
                        results.Add((type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat), part1, part2));
                    }
                }
            }
        });

        context.RegisterSourceOutput(answers, static (output, answer) =>
        {
            // Escape underscores before encoding namespace separators to keep names distinct.
            var testName = answer.TypeName.Substring("global::".Length)
                .Replace("_", "__").Replace(".", "_0").Replace("@", "");

            var source = new StringBuilder("""
                                           // <auto-generated />
                                           namespace AdventOfCode.Tests.Generated;

                                           public partial class GeneratedAocTests
                                           {

                                           """);

            if (answer.Part1 is not null)
            {
                AppendTest(1, answer.Part1);
            }

            if (answer.Part2 is not null)
            {
                AppendTest(2, answer.Part2);
            }

            source.AppendLine("}");
            output.AddSource($"{testName}.g.cs", source.ToString());

            void AppendTest(int part, string expected)
            {
                source.AppendLine($$"""
                                        [global::Xunit.Fact]
                                        [global::Xunit.Trait("Category", "RealInput")]
                                        public async global::System.Threading.Tasks.Task {{testName}}_Part{{part}}_real_input_matches_expected()
                                        {
                                            var day = new {{answer.TypeName}}();
                                            var result = await day.Solve_{{part}}();
                                            global::Xunit.Assert.Equal({{SymbolDisplay.FormatLiteral(expected, quote: true)}}, result);
                                        }

                                    """);
            }
        });
    }

    private static bool DerivesFrom(INamedTypeSymbol type, INamedTypeSymbol baseType)
    {
        for (var current = type.BaseType; current is not null; current = current.BaseType)
        {
            if (SymbolEqualityComparer.Default.Equals(current, baseType))
            {
                return true;
            }
        }

        return false;
    }
}
